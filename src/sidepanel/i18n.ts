const dictionary: Record<EffectiveLocale, SidepanelText> = {
  'zh-CN': zhCN,
  en,
};

export function getDefaultLocale(): EffectiveLocale {
  const language = chrome.i18n?.getUILanguage?.() || navigator.language || '';
  const normalized = language.toLowerCase();
  if (normalized.startsWith('en')) return 'en';
  return 'zh-CN';
}

export function resolveLocale(locale: AppLocale): EffectiveLocale {
  return locale === 'system' ? getDefaultLocale() : locale;
}

export function getSidepanelText(locale: AppLocale): SidepanelText {
  return dictionary[resolveLocale(locale)];
}

export function interpolate(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ''));
}
